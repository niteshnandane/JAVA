package dsa.java.Operators;

public class BitewiseOperator {
    static void main() {
     int p=9,q=10;
        System.out.println(p | q);
        System.out.println(p & q);
        System.out.println(p ^ q);

        System.out.println(p  << 1);
        System.out.println( p << 2);
        System.out.println(p >> 1);
        System.out.println(p >> 2);
    }
}
