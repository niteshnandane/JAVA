package dsa.java.Operators;

public class RelationalOpreators {
    static void main() {
        int p=10,q=15;
        System.out.println(p == q);
        System.out.println(p != q);
        System.out.println(p <= q);
        System.out.println(p >= q);
        System.out.println(p < q);
        System.out.println(p > q);
    }
}
